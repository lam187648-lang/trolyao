const test = require("node:test");
const assert = require("node:assert/strict");
const { startServer } = require("./helpers");

test("existing auth, token, theme and admin APIs keep working", async (t) => {
  const s = await startServer();
  t.after(() => s.stop());
  const { api } = s;
  const name = `reg${Date.now().toString(36)}`;
  let r;

  r = await api("/auth/status");
  assert.ok(r.data.databaseConfigured && r.data.migrationApplied, "database + migration 001");
  r = await api("/auth/register", { method: "POST", body: { username: name, password: "short" } });
  assert.equal(r.status, 400, "short password rejected");
  r = await api("/auth/register", { method: "POST", body: { username: name, password: "password123", role: "admin" } });
  assert.equal(r.status, 201);
  assert.equal(r.data.user.role, "user", "forged role ignored");
  const A = r.data.accessToken;
  const aliceId = r.data.user.id;
  r = await api("/auth/register", { method: "POST", body: { username: name.toUpperCase(), password: "password123" } });
  assert.equal(r.status, 409, "duplicate username (case-insensitive)");
  r = await api("/auth/login", { method: "POST", body: { username: name, password: "wrongpass" } });
  assert.equal(r.status, 401, "wrong password");
  r = await api("/auth/me", { token: A });
  assert.equal(r.data.user.username, name);
  assert.equal((await api("/api/balance")).status, 401, "balance requires auth");
  assert.equal((await api("/api/balance", { token: A })).data.tokenBalance, 0);
  assert.equal((await api("/api/themes/14/purchase", { method: "POST", token: A })).status, 409, "insufficient tokens");
  assert.equal((await api("/api/themes/17/purchase", { method: "POST", token: A })).status, 403, "admin-only theme");
  assert.equal((await api("/api/themes/selected", { method: "PUT", token: A, body: { themeId: "17" } })).status, 403);
  assert.equal((await api("/api/themes/selected", { method: "PUT", token: A, body: { themeId: "3" } })).status, 200);
  assert.equal((await api("/api/study-reward", { method: "POST", token: A })).data.tokenBalance, 20, "study reward +20");
  assert.equal((await api("/api/study-reward", { method: "POST", token: A })).status, 429, "study reward cooldown");
  assert.equal((await api("/admin/users", { token: A })).status, 403, "non-admin blocked");
  assert.equal((await api("/admin/users")).status, 401, "anonymous blocked");
  assert.equal((await api("/admin/db-diagnostic")).status, 401, "diagnostic needs secret");
  assert.equal((await api("/pusher/kick", { method: "POST" })).status, 403);

  const bob = await s.register("rb");
  await s.promote(aliceId);
  assert.equal((await api("/admin/users", { token: A })).status, 200, "admin list");
  assert.equal((await api(`/admin/users/${bob.id}/tokens`, { method: "POST", token: A, body: { amount: -5 } })).status, 400);
  r = await api(`/admin/users/${bob.id}/tokens`, { method: "POST", token: A, body: { amount: 60, note: "test" } });
  assert.equal(Number(r.data.user.token_balance), 60);
  assert.equal((await api("/api/themes/14/purchase", { method: "POST", token: bob.token })).data.tokenBalance, 10);
  assert.equal((await api("/api/themes/14/purchase", { method: "POST", token: bob.token })).data.tokenBalance, 10, "no double charge");
  assert.equal((await api("/api/transactions", { token: bob.token })).data.transactions.length, 2);
  assert.equal((await api(`/admin/users/${bob.id}/themes/17`, { method: "POST", token: A })).status, 204);
  assert.equal((await api("/api/themes/selected", { method: "PUT", token: bob.token, body: { themeId: "17" } })).status, 200);
  assert.equal((await api(`/admin/users/${bob.id}/status`, { method: "PATCH", token: A, body: { status: "locked" } })).status, 200);
  assert.equal((await api("/auth/me", { token: bob.token })).status, 401, "lock revokes sessions");
  assert.equal((await api("/auth/login", { method: "POST", body: { username: bob.username, password: bob.password } })).status, 403);
  assert.equal((await api(`/admin/users/${bob.id}/status`, { method: "PATCH", token: A, body: { status: "active" } })).status, 200);
  assert.ok((await api("/admin/audit", { token: A })).data.logs.length >= 4);
  assert.equal((await api("/auth/logout", { method: "POST", token: A })).status, 204);
  assert.equal((await api("/auth/me", { token: A })).status, 401, "logout invalidates token");
  r = await api("/chat", { method: "POST", body: { messages: [{ role: "user", content: "hi" }] } });
  assert.equal(r.status, 500);
  assert.match(r.data.error, /OPENROUTER/);
});
